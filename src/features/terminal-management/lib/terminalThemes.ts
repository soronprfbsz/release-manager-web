/**
 * 앱 테마에 맞는 터미널 테마 가져오기
 */
export function getTerminalTheme(appTheme: Theme): ITheme {
  if (appTheme === 'system') {
    const isDark = window.matchMedia('(prefers-color-scheme: dark)').matches
    return isDark ? terminalThemes.dark : terminalThemes.light
  }
  return terminalThemes[appTheme]
}
